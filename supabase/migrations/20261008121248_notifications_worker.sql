-- Story 3.4: claim, recheck and retry jobs with a leased and fenced worker (AD-8, AD-17, AD-19;
-- epic 3 requirement N4). Builds on 20261008073631_notifications_inbox.sql,
-- 20261008090057_notifications_source_contracts.sql and 20261008102121_notifications_scheduling.sql.
--
--   * Central worker policy `app.notifications_worker_settings` (one row, operator-set through
--     app.notifications_configure_worker): lease length, batch size, attempt limit, backoff
--     (base doubling to a maximum) and the default expiry of a job without its own `expires_at`.
--   * Three system commands of the purpose `notifications_worker` (1.9 system route):
--       notifications.claim {limit?}   counts every lapsed lease that recorded no attempt as a
--                                      `lapsed` attempt (it may have timed out or crashed) and
--                                      frees it, ends expired pending jobs (`obsolete`,
--                                      `expired`), then leases a bounded batch of due jobs
--                                      (`for update skip locked`). Each lease takes a fresh
--                                      fencing token from one monotonic sequence. Answers the
--                                      opaque {job_id, lease_token} pairs and counts.
--       notifications.attempt {job_id, lease_token}
--                                      fences (the token must be the job's current one and the
--                                      lease still live), then rechecks expiry, the source and
--                                      revision, actionability, the approved schedule, the
--                                      source's view of the recipient and the recipient's
--                                      membership before writing the one inbox item. A recheck
--                                      that raises, or is cancelled by a statement timeout, is a
--                                      transient failure: the lease is released and the job
--                                      backs off; when failures plus lapses reach the attempt
--                                      limit it ends `obsolete` (`attempts_exhausted`). Every
--                                      attempt is one content-free row in
--                                      `app.notifications_attempts`.
--       notifications.release {job_id, lease_token}
--                                      gives back a live lease the worker will not use (no
--                                      attempt is counted).
--     `job_state` keeps its story 3.1 values; the new `finish_reason` says why a job ended.
--   * `notifications.deliver_due` (story 3.1) becomes claim + attempt in one transaction, with
--     the same rules, at most `batch_max` jobs and the same five counts.
--   * Scheduler: the Cron job runs app.notifications_scheduler_tick(), which posts to the Edge
--     Function `notifications-worker` (URL in the settings, pinned per environment) with pg_net
--     and a low-value TRIGGER token read from Supabase Vault (`notifications_worker_trigger`,
--     generated by app.notifications_scheduler_new_trigger). The trigger can only start one
--     idempotent run. The worker's system credential never enters the database: it is an Edge
--     Function secret set by the owner. The Cron command text holds no secret. Operator
--     functions create the one named job of this environment (app.notifications_scheduler_enable,
--     every minute or every 15-59 seconds), remove it (app.notifications_scheduler_disable) and
--     report it (app.notifications_scheduler_status). Nothing here creates a schedule.
--     Production needs ops_system_access, q2_church_time and q12_operations before a tick or an
--     enable does anything.
--   * Operator actions (policy changes, scheduler enable/disable, trigger rotation) are recorded
--     in app.ops_operator_actions. Its action CHECK is widened by the retire-by-rename pattern of
--     stories 2.3 and 2.12 (ops_retired_operator_actions_v2, rows copied).
--   * SYNTHETIC: `fixture_reminder_sources.check_fault_until` (set by SQL only) makes the
--     fixture's reminder check raise until that instant, to show a transient failure.
--
-- No destructive statements and no row deletions. No anon grant. ASCII only.

