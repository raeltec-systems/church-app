-- notifications.deliver_due (story 3.1) is now claim + attempt in one transaction: the same
-- leases, rechecks, retries and expiry, at most batch_max jobs, answering the same five counts
-- (claimed counts the jobs it leased plus those it expired; obsolete includes expired and
-- exhausted ones). After a statement-timeout cancel it releases the remaining leases unused and
-- stops, so the rest of the batch is not run without a timeout.
create or replace function app.notifications_sys_deliver_due(p_principal uuid, p_request uuid, p_payload jsonb)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_settings app.notifications_worker_settings := app.notifications_worker_config();
  v_claim jsonb;
  v_entry jsonb;
  v_result jsonb;
  v_stop boolean := false;
  v_delivered integer := 0;
  v_obsolete integer := 0;
  v_ineligible integer := 0;
  v_failed integer := 0;
begin
  v_claim := app.notifications_claim(p_principal, p_request,
                                     least(coalesce((p_payload ->> 'limit')::numeric::integer, 50),
                                           v_settings.batch_max),
                                     'deliver_due');
  v_obsolete := (v_claim ->> 'expired')::integer;
  for v_entry in select e from jsonb_array_elements(v_claim -> 'jobs') e loop
    if v_stop then
      perform app.notifications_release(p_principal, (v_entry ->> 'job_id')::uuid,
                                        (v_entry ->> 'lease_token')::bigint);
      continue;
    end if;
    v_result := app.notifications_attempt(p_principal, p_request, (v_entry ->> 'job_id')::uuid,
                                          (v_entry ->> 'lease_token')::bigint);
    case v_result ->> 'outcome'
      when 'delivered' then v_delivered := v_delivered + 1;
      when 'ineligible' then v_ineligible := v_ineligible + 1;
      when 'failed' then v_failed := v_failed + 1;
      else v_obsolete := v_obsolete + 1;
    end case;
    v_stop := (v_result ->> 'sqlstate') = '57014';
  end loop;
  return jsonb_build_object('data', jsonb_build_object(
    'claimed', (v_claim ->> 'claimed')::integer + (v_claim ->> 'expired')::integer,
    'delivered', v_delivered, 'obsolete', v_obsolete, 'ineligible', v_ineligible,
    'failed', v_failed));
end;
$$;

